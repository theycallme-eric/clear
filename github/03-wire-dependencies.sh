#!/usr/bin/env bash
# 03 — wire blocked-by relationships. Needs gh 2.94.0+.
# Run AFTER 02. Safe to re-run; GitHub ignores duplicate relationships.
set -euo pipefail
REPO="${1:-}"
[ -z "$REPO" ] && { echo "usage: ./03-wire-dependencies.sh owner/repo" >&2; exit 1; }
export GH_REPO="$REPO"
cd "$(dirname "${BASH_SOURCE[0]}")"
MAP="issue-map.txt"
[ -s "$MAP" ] || { echo "issue-map.txt missing or empty — run 02 first" >&2; exit 1; }

num_for() { grep "^$1 " "$MAP" | awk '{print $2}'; }

FAILED=0
wire() {
  local child_id="$1" parent_id="$2"
  local child parent
  child=$(num_for "$child_id"); parent=$(num_for "$parent_id")
  if [ -z "$child" ] || [ -z "$parent" ]; then
    echo "  ?? $child_id ← $parent_id (missing from map)"; FAILED=$((FAILED+1)); return 0
  fi
  if gh issue edit "$child" --add-blocked-by "$parent" >/dev/null 2>&1; then
    echo "  #$child blocked by #$parent   ($child_id ← $parent_id)"
  else
    echo "  FAIL #$child ← #$parent   ($child_id ← $parent_id)"; FAILED=$((FAILED+1))
  fi
}

