/**
 * @param {readonly string[]} values
 * @returns {string} A Postgres array literal, which coerces to `text[]` or to
 *   an enum array without this file naming the type.
 */
function toPgArray(values) {
  return `{${values.map((value) => `"${value.replaceAll('"', '\\"')}"`).join(',')}}`
}
